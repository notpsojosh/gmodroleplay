function GM:Initialize()
    print("[" .. PDCity.BRAND_TAG .. "] Server Initialize")
end

hook.Add("PlayerSpawn", "pdcity_SpawnStats", function(ply)
    ply:SetHealth(100)
    ply:SetArmor(0)
end)

function GM:PlayerLoadout(ply)
    PDCity.GiveJobWeapons(ply)
    return true
end

-- F1 / F4 menus. The engine fires these via the native gm_showhelp /
-- gm_showspare2 concommands (bound to F1/F4 by default), same mechanism
-- base gamemode uses for GM:ShowTeam. Player:ConCommand forwards to a
-- client concommand rather than Player:SendLua, since most clients have
-- "allow this server to run Lua on my client" off and would never see it.
function GM:ShowHelp(ply)
    if IsValid(ply) then ply:ConCommand("pdcity_showhelp") end
end

function GM:ShowSpare2(ply)
    if IsValid(ply) then ply:ConCommand("pdcity_showjobs") end
end

function GM:PlayerDeath(victim, inflictor, attacker)
    print(victim:Nick() .. " died.")
end